"""Writes the rendered heightfields as OBJ meshes (assets/lunar_hfield_visual.obj, lunar_far_hfield.obj).

Offline; run manually and commit the output.

nyx_export_scene drops hfield geoms, so the path-traced cameras would show the ground as empty
space. The two rendered hfields (ground_visual and far_horizon) are drawn from these meshes instead,
which both renderers support; the driven hfield stays an hfield, in group 3, so contact is
untouched. Vertices come from MuJoCo's own compiled hfield, so each mesh is the surface MuJoCo
drew, vertex for vertex. Texture coordinates tile the regolith colour map as regolith_ground tiles
it on the hfield: with texuniform, MuJoCo repeats a texture every 2 / texrepeat metres.

Re-run whenever generate_visual_terrain.py or generate_far_terrain.py regenerates its hfield.

Usage: python3 generate_terrain_meshes.py
"""
from pathlib import Path

import mujoco
import numpy as np

HERE = Path(__file__).resolve().parent
ASSETS = HERE / "assets"
HFIELDS = ("lunar_hfield_visual", "lunar_far_hfield")
HFIELD_MATERIAL = "regolith_ground"


def hfield_vertices(model: mujoco.MjModel, hid: int) -> tuple[np.ndarray, int, int]:
    """The hfield's surface vertices in its geom frame, row-major from -y to +y."""
    nrow, ncol = int(model.hfield_nrow[hid]), int(model.hfield_ncol[hid])
    sx, sy, sz, _ = model.hfield_size[hid]
    adr = int(model.hfield_adr[hid])
    height = model.hfield_data[adr : adr + nrow * ncol].reshape(nrow, ncol) * sz
    y, x = np.meshgrid(
        np.linspace(-sy, sy, nrow), np.linspace(-sx, sx, ncol), indexing="ij"
    )
    return np.stack([x, y, height], axis=-1).reshape(-1, 3), nrow, ncol


def write_obj(
    path: Path, vertices: np.ndarray, nrow: int, ncol: int, tile_m: np.ndarray
) -> None:
    uv = vertices[:, :2] / tile_m + 0.5
    idx = np.arange(nrow * ncol).reshape(nrow, ncol) + 1
    a, b, c, d = idx[:-1, :-1], idx[:-1, 1:], idx[1:, 1:], idx[1:, :-1]
    # Counter-clockwise seen from +z, so the faces point up.
    faces = np.concatenate([np.stack([a, b, c], -1), np.stack([a, c, d], -1)]).reshape(
        -1, 3
    )
    with path.open("w", encoding="utf-8") as out:
        out.write(
            f"# generated by generate_terrain_meshes.py from hfield {path.stem}\n"
        )
        out.writelines(f"v {x:.5f} {y:.5f} {z:.5f}\n" for x, y, z in vertices)
        out.writelines(f"vt {u:.6f} {v:.6f}\n" for u, v in uv)
        out.writelines(f"f {i}/{i} {j}/{j} {k}/{k}\n" for i, j, k in faces)


def main() -> None:
    model = mujoco.MjModel.from_xml_path(str(HERE / "husky_scene.xml"))
    # Measured: a texuniform plane or hfield with texrepeat R shows one texture tile per 2 / R m.
    tile_m = 2.0 / np.asarray(
        model.mat_texrepeat[model.material(HFIELD_MATERIAL).id], dtype=float
    )
    for name in HFIELDS:
        vertices, nrow, ncol = hfield_vertices(model, model.hfield(name).id)
        path = ASSETS / f"{name}.obj"
        write_obj(path, vertices, nrow, ncol, tile_m)
        print(
            f"wrote {path.name}: {len(vertices)} vertices, {2 * (nrow - 1) * (ncol - 1)} faces"
        )


if __name__ == "__main__":
    main()
