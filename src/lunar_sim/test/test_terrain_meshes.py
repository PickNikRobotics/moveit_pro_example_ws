"""The drawn terrain meshes must match the heightfields they were generated from.

Nyx's exporter drops heightfields, so the visual terrain is drawn as OBJ meshes generated by
description/generate_terrain_meshes.py. If a heightfield is regenerated without re-running that
script, the drawn terrain and the collision terrain silently diverge.
"""

import importlib.util
from pathlib import Path

import mujoco
import numpy as np
import pytest
from ament_index_python.packages import get_package_share_directory

DESCRIPTION = Path(get_package_share_directory("lunar_sim")) / "description"


def _generator():
    spec = importlib.util.spec_from_file_location(
        "generate_terrain_meshes", DESCRIPTION / "generate_terrain_meshes.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GENERATOR = _generator()


@pytest.fixture(scope="module")
def model():
    return mujoco.MjModel.from_xml_path(str(DESCRIPTION / "husky_scene.xml"))


def _obj_vertices(path: Path) -> np.ndarray:
    with path.open(encoding="utf-8") as obj:
        return np.array(
            [
                [float(v) for v in line.split()[1:4]]
                for line in obj
                if line.startswith("v ")
            ]
        )


@pytest.mark.parametrize("name", GENERATOR.HFIELDS)
def test_each_terrain_mesh_matches_its_heightfield(model, name):
    expected, nrow, ncol = GENERATOR.hfield_vertices(model, model.hfield(name).id)
    drawn = _obj_vertices(DESCRIPTION / "assets" / f"{name}.obj")
    assert drawn.shape == (
        nrow * ncol,
        3,
    ), f"re-run generate_terrain_meshes.py: {name} changed size"
    # The OBJ stores 5 decimals, so 10 um bounds the rounding.
    assert (
        np.abs(drawn - expected).max() < 1e-5
    ), f"re-run generate_terrain_meshes.py: {name} changed"
